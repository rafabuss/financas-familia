const now = new Date();
const currentYear = now.getFullYear();
const currentMonthNum = now.getMonth() + 1;
const pad = (n) => String(n).padStart(2, '0');

/**
 * Retorna uma chave de mês 'YYYY-MM' calculada a partir de um deslocamento (offset)
 * em relação ao mês corrente (0 = atual, -1 = mês anterior, 1 = próximo mês, etc.).
 */
export const getRelativeMonthKey = (offset = 0) => {
  const d = new Date(currentYear, currentMonthNum - 1 + offset, 1);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}`;
};

/**
 * Retorna uma data ISO 'YYYY-MM-DD' para um dia específico e deslocamento de mês.
 */
export const getRelativeDate = (offsetMonth, day) => {
  const mKey = getRelativeMonthKey(offsetMonth);
  return `${mKey}-${pad(day)}`;
};

